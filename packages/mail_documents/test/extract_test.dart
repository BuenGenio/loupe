import 'dart:convert';
import 'dart:io' show ZLibEncoder;
import 'dart:math';
import 'dart:typed_data';

import 'package:mail_documents/mail_documents.dart';
import 'package:test/test.dart';

import 'pdf_fixtures.dart';

ExtractedDocument pdf(Uint8List bytes, [ExtractionLimits limits = const ExtractionLimits()]) =>
    readDocument(bytes, mimeType: 'application/pdf', fileName: 'a.pdf', limits: limits);

/// A PDF written like the demo's (`pagedPdf`): Helvetica without an
/// encoding, one text object per line, a title on every page.
Uint8List demoStylePdf(String title, List<List<String>> pages) => pdfWithPages([
  for (final (i, lines) in pages.indexed)
    [
      'BT /F1 24 Tf 72 720 Td ($title) Tj ET',
      for (final (k, l) in lines.indexed) 'BT /F1 14 Tf 72 ${680 - 26 * k} Td ($l) Tj ET',
      'BT /F1 10 Tf 72 60 Td (Page ${i + 1} of ${pages.length} - demo document generated by Loupe) Tj ET',
    ].join('\n'),
], font: '<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica >>');

void main() {
  group('PDF text', () {
    test('pages in page-tree order, one line per text line', () {
      final doc = pdf(
        demoStylePdf('Mortgage illustration', [
          ['Loan amount: GBP 285,000', 'Initial rate: 4.19% fixed for 5 years'],
          ['Arrangement fee: GBP 1,499 (payable on completion)'],
        ]),
      );
      expect(doc.status, ExtractionStatus.complete);
      expect(doc.format, DocumentFormat.pdf);
      expect(doc.pageCount, 2);
      expect(doc.pages.map((p) => p.number), [1, 2]);
      expect(
        doc.pages[0].text,
        'Mortgage illustration\nLoan amount: GBP 285,000\nInitial rate: 4.19% fixed for 5 years\n'
        'Page 1 of 2 - demo document generated by Loupe',
      );
      expect(doc.pages[1].text, contains('Arrangement fee: GBP 1,499 (payable on completion)'));
      expect(doc.pageText(2), contains('1,499'));
      expect(doc.pageText(3), isNull);
      expect(
        doc.contentHash,
        contentHash(
          demoStylePdf('Mortgage illustration', [
            ['Loan amount: GBP 285,000', 'Initial rate: 4.19% fixed for 5 years'],
            ['Arrangement fee: GBP 1,499 (payable on completion)'],
          ]),
        ),
      );
    });

    test('Flate-compressed content streams', () {
      final doc = pdf(pdfWithPages([line('Compressed text, page one'), line('And page two')], compress: true));
      expect(doc.status, ExtractionStatus.complete);
      expect(doc.pages.map((p) => p.text), ['Compressed text, page one', 'And page two']);
    });

    test('TJ arrays: kerning stays inside words, wide gaps are spaces', () {
      final doc = pdf(
        pdfWithPages(['BT /F1 12 Tf 72 700 Td [(Amo) -20 (unt) -400 (due) 120 (:) -300 (GBP 450.00)] TJ ET']),
      );
      expect(doc.pages.single.text, 'Amount due: GBP 450.00');
    });

    test('hex strings, octal escapes and the quote operators', () {
      final doc = pdf(
        pdfWithPages([
          'BT /F1 12 Tf 14 TL 72 700 Td <496E766F696365> Tj T* (Total \\050net\\051: \\243 12) Tj (next) \' 1 2 (last) " ET',
        ]),
      );
      expect(doc.pages.single.text, 'Invoice\nTotal (net): £ 12\nnext\nlast');
    });

    test('a line moved along with Td gets a space, a new line with T* a break', () {
      final doc = pdf(
        pdfWithPages(['BT /F1 12 Tf 72 700 Td (Date:) Tj 40 0 Td (10 November) Tj 0 -14 Td (Time: 10:00) Tj ET']),
      );
      expect(doc.pages.single.text, 'Date: 10 November\nTime: 10:00');
    });

    test('Tm positions: same baseline joins, another baseline breaks', () {
      final doc = pdf(
        pdfWithPages([
          'BT /F1 1 Tf 12 0 0 12 72 700 Tm (Left) Tj 12 0 0 12 200 700 Tm (Right) Tj 12 0 0 12 72 680 Tm (Below) Tj ET',
        ]),
      );
      expect(doc.pages.single.text, 'Left Right\nBelow');
    });

    test('WinAnsi and Differences decode non-ASCII letters', () {
      final win = pdf(pdfWithPages([line('Caf\\351 \\200 5 \\226 \\223quoted\\224')]));
      expect(win.pages.single.text, 'Café € 5 – “quoted”');
      final diff = pdf(
        pdfWithPages(
          [line('\\001\\002 ok')],
          font: '<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica /Encoding << /Type /Encoding /BaseEncoding /WinAnsiEncoding /Differences [1 /Euro /fi] >> >>',
        ),
      );
      expect(diff.pages.single.text, '€ﬁ ok');
    });

    test('Type0 fonts read through their ToUnicode map; without one they give no text', () {
      const cmap =
          '/CIDInit /ProcSet findresource begin 12 dict begin begincmap\n'
          '1 begincodespacerange <0000> <FFFF> endcodespacerange\n'
          '2 beginbfchar <0003> <0020> <0011> <00E9> endbfchar\n'
          '1 beginbfrange <0024> <0026> <0041> endbfrange\n'
          '1 beginbfrange <0030> <0031> [<0052> <0061>] endbfrange\n'
          'endcmap CMapName currentdict /CMap defineresource pop end end';
      final b = PdfBuilder();
      final catalog = b.reserve();
      final pages = b.reserve();
      final toUnicode = b.stream('', latin1.encode(cmap), compress: true);
      final font = b.add(
        '<< /Type /Font /Subtype /Type0 /BaseFont /ABCDEF+Some /Encoding /Identity-H /ToUnicode $toUnicode 0 R >>',
      );
      final bare = b.add('<< /Type /Font /Subtype /Type0 /BaseFont /Other /Encoding /Identity-H >>');
      final content = b.stream(
        '',
        latin1.encode(
          'BT /F1 12 Tf 72 700 Td <00240025002600030011003000310030> Tj /F2 12 Tf 0 -20 Td <00240025> Tj ET',
        ),
      );
      final page = b.add(
        '<< /Type /Page /Parent $pages 0 R /Contents $content 0 R /Resources << /Font << /F1 $font 0 R /F2 $bare 0 R >> >> >>',
      );
      b
        ..set(catalog, '<< /Type /Catalog /Pages $pages 0 R >>')
        ..set(pages, '<< /Type /Pages /Kids [$page 0 R] /Count 1 >>');
      final doc = pdf(b.build());
      expect(doc.pages.single.text, 'ABC éRaR');
    });

    test('Resources and Kids inherited through intermediate nodes; contents as an array', () {
      final b = PdfBuilder();
      final catalog = b.reserve();
      final root = b.reserve();
      final middle = b.reserve();
      final font = b.add('<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica >>');
      final c1 = b.stream('', latin1.encode('BT /F1 12 Tf 72 700 Td (first'));
      final c2 = b.stream('', latin1.encode(') Tj ET'));
      final c3 = b.stream('', latin1.encode(line('second')));
      final p1 = b.add('<< /Type /Page /Parent $middle 0 R /Contents [$c1 0 R $c2 0 R] >>');
      final p2 = b.add('<< /Type /Page /Parent $root 0 R /Contents $c3 0 R >>');
      b
        ..set(catalog, '<< /Type /Catalog /Pages $root 0 R >>')
        ..set(
          root,
          '<< /Type /Pages /Kids [$middle 0 R $p2 0 R] /Count 2 /Resources << /Font << /F1 $font 0 R >> >> >>',
        )
        ..set(middle, '<< /Type /Pages /Parent $root 0 R /Kids [$p1 0 R] /Count 1 >>');
      final doc = pdf(b.build());
      expect(doc.pages.map((p) => p.text), ['first', 'second']);
    });

    test('form XObjects are read; inline images are skipped', () {
      final b = PdfBuilder();
      final catalog = b.reserve();
      final pages = b.reserve();
      final font = b.add('<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica >>');
      final form = b.stream(
        '/Type /XObject /Subtype /Form /BBox [0 0 100 100]',
        latin1.encode(line('In a form', y: 600)),
      );
      final content = b.stream('', [
        ...latin1.encode('${line('Before')}BI /W 2 /H 2 /BPC 8 /CS /G ID '),
        0x28, 0x00, 0xFF, 0x29, // binary that looks like a string
        ...latin1.encode(' EI\n/X1 Do\n'),
      ]);
      final page = b.add(
        '<< /Type /Page /Parent $pages 0 R /Contents $content 0 R /Resources << /Font << /F1 $font 0 R >> /XObject << /X1 $form 0 R >> >> >>',
      );
      b
        ..set(catalog, '<< /Type /Catalog /Pages $pages 0 R >>')
        ..set(pages, '<< /Type /Pages /Kids [$page 0 R] /Count 1 >>');
      expect(pdf(b.build()).pages.single.text, 'Before\nIn a form');
    });

    test('objects inside object streams (PDF 1.5)', () {
      final b = PdfBuilder();
      final content = b.stream('', latin1.encode(line('From an object stream')));
      // Objects 3 (catalog), 4 (pages), 5 (page) and 6 (font) live in the object stream.
      final objects = [
        '<< /Type /Catalog /Pages 4 0 R >>',
        '<< /Type /Pages /Kids [5 0 R] /Count 1 >>',
        '<< /Type /Page /Parent 4 0 R /Contents $content 0 R /Resources << /Font << /F1 6 0 R >> >> >>',
        '<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica >>',
      ];
      final body = StringBuffer();
      final header = StringBuffer();
      for (final (i, o) in objects.indexed) {
        header.write('${3 + i} ${body.length} ');
        body.write('$o\n');
      }
      final first = header.length;
      b.stream('/Type /ObjStm /N ${objects.length} /First $first', latin1.encode('$header$body'), compress: true);
      expect(b.reserve(), 3);
      for (var i = 0; i < 3; i++) {
        b.reserve();
      }
      final bytes = b.build(root: 3);
      // The builder wrote "3 0 obj null" for the reserved numbers; drop them
      // so only the object stream defines them.
      final text = latin1.decode(bytes).replaceAll(RegExp(r'\n[3-6] 0 obj\nnull\nendobj'), '\n');
      final doc = pdf(Uint8List.fromList(latin1.encode(text)));
      expect(doc.status, ExtractionStatus.complete, reason: '${doc.status}');
      expect(doc.pages.single.text, 'From an object stream');
    });

    test('an incremental update replaces an earlier definition of a page', () {
      // Object 4 is the page's content stream; the update appends a new one.
      final original = pdfWithPages([line('Old figure: 4.29%')]);
      final content = line('New figure: 4.19%');
      final update = '\n4 0 obj\n<< /Length ${content.length} >>\nstream\n${content}endstream\nendobj\n';
      final doc = pdf(Uint8List.fromList([...original, ...latin1.encode(update)]));
      expect(doc.pages.single.text, 'New figure: 4.19%');
    });

    test('no text on any page: probably a scan', () {
      final doc = pdf(pdfWithPages(['q 612 0 0 792 0 0 cm /Im1 Do Q', '0 0 m 100 100 l S']));
      expect(doc.status, ExtractionStatus.noText);
      expect(doc.pageCount, 2);
      expect(doc.searchable, isFalse);
    });

    test('a page with an unsupported filter is unread, and the document partial', () {
      final b = PdfBuilder();
      final catalog = b.reserve();
      final pages = b.reserve();
      final font = b.add('<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica >>');
      final good = b.stream('', latin1.encode(line('Readable page')));
      final lzw = b.add('<< /Length 4 /Filter /LZWDecode >>\nstream\nabcd\nendstream');
      final p1 = b.add(
        '<< /Type /Page /Parent $pages 0 R /Contents $good 0 R /Resources << /Font << /F1 $font 0 R >> >> >>',
      );
      final p2 = b.add('<< /Type /Page /Parent $pages 0 R /Contents $lzw 0 R >>');
      b
        ..set(catalog, '<< /Type /Catalog /Pages $pages 0 R >>')
        ..set(pages, '<< /Type /Pages /Kids [$p1 0 R $p2 0 R] /Count 2 >>');
      final doc = pdf(b.build());
      expect(doc.status, ExtractionStatus.partial);
      expect(doc.limit, isNull);
      expect(doc.pages[1].readable, isFalse);
      expect(doc.pagesRead, 1);
      expect(doc.pagesNotRead, 1);
    });
  });

  group('documents that can’t be read', () {
    test('password protected: nothing is read', () {
      final doc = pdf(
        pdfWithPages([
          line('Secret'),
        ], trailerExtra: ' /Encrypt << /Filter /Standard /V 2 /R 3 /O <00> /U <00> /P -4 >>'),
      );
      expect(doc.status, ExtractionStatus.encrypted);
      expect(doc.pages, isEmpty);
    });

    test('encryption named in a cross-reference stream counts too', () {
      final base = latin1.decode(pdfWithPages([line('Secret')]));
      final xref =
          '\n9 0 obj\n<< /Type /XRef /Size 10 /Root 1 0 R /Encrypt 8 0 R /W [1 2 1] /Length 0 >>\nstream\n\nendstream\nendobj\n';
      expect(pdf(Uint8List.fromList(latin1.encode('$base$xref'))).status, ExtractionStatus.encrypted);
    });

    test('larger than the limit: not read at all', () {
      final doc = pdf(pdfWithPages([line('Big')]), const ExtractionLimits(maxBytes: 100));
      expect(doc.status, ExtractionStatus.tooLarge);
      expect(doc.contentHash, hasLength(64));
    });

    test('a page limit keeps the first pages and says how many there are', () {
      final doc = pdf(
        pdfWithPages([for (var i = 1; i <= 5; i++) line('Page $i')]),
        const ExtractionLimits(maxPages: 2),
      );
      expect(doc.status, ExtractionStatus.partial);
      expect(doc.limit, ExtractionLimit.pages);
      expect(doc.pages.map((p) => p.text), ['Page 1', 'Page 2']);
      expect(doc.pageCount, 5);
      expect(doc.pagesNotRead, 3);
    });

    test('a Flate bomb stops at the decoded-bytes limit', () {
      final bomb = ZLibEncoder().convert(List.filled(8 << 20, 0x20));
      final b = PdfBuilder();
      final catalog = b.reserve();
      final pages = b.reserve();
      final content = b.add(
        '<< /Length ${bomb.length} /Filter /FlateDecode >>\nstream\n${latin1.decode(bomb)}\nendstream',
      );
      final page = b.add('<< /Type /Page /Parent $pages 0 R /Contents $content 0 R >>');
      b
        ..set(catalog, '<< /Type /Catalog /Pages $pages 0 R >>')
        ..set(pages, '<< /Type /Pages /Kids [$page 0 R] /Count 1 >>');
      final doc = pdf(b.build(), const ExtractionLimits(maxDecodedBytes: 1 << 20));
      expect(doc.status, ExtractionStatus.partial);
      expect(doc.limit, ExtractionLimit.decodedBytes);
    });

    test('an operator limit stops a long content stream', () {
      final doc = pdf(pdfWithPages([List.filled(5000, line('x')).join()]), const ExtractionLimits(maxOperators: 1000));
      expect(doc.status, ExtractionStatus.partial);
      expect(doc.limit, ExtractionLimit.operators);
    });

    test('not a PDF, or nothing but a header: damaged', () {
      expect(pdf(Uint8List.fromList(utf8.encode('hello'))).status, ExtractionStatus.damaged);
      expect(pdf(Uint8List.fromList(utf8.encode('%PDF-1.4\n'))).status, ExtractionStatus.damaged);
      expect(pdf(Uint8List(0)).status, ExtractionStatus.damaged);
    });

    test('a Word document is unsupported, a PDF sent as octet-stream is read', () {
      final docx = readDocument(
        Uint8List.fromList([0x50, 0x4B, 3, 4]),
        mimeType: 'application/vnd.openxmlformats-officedocument.wordprocessingml.document',
        fileName: 'agenda.docx',
      );
      expect(docx.status, ExtractionStatus.unsupported);
      expect(docx.format, isNull);
      final sniffed = readDocument(
        pdfWithPages([line('Sniffed')]),
        mimeType: 'application/octet-stream',
        fileName: 'scan',
      );
      expect(sniffed.pages.single.text, 'Sniffed');
    });
  });

  group('hostile input never throws', () {
    final good = pdfWithPages([line('Initial rate: 4.19% fixed'), line('Amount due: GBP 450.00')], compress: true);
    final random = Random(7);

    test('every truncation of a valid file', () {
      for (var n = 0; n < good.length; n += 7) {
        final doc = pdf(Uint8List.sublistView(good, 0, n));
        expect(ExtractionStatus.values, contains(doc.status));
      }
    });

    test('random bytes, with and without a header', () {
      for (var i = 0; i < 300; i++) {
        final junk = Uint8List.fromList(List.generate(random.nextInt(4000), (_) => random.nextInt(256)));
        pdf(junk);
        pdf(Uint8List.fromList([...latin1.encode('%PDF-1.4\n1 0 obj\n'), ...junk]));
      }
    });

    test('mutated bytes of a valid file', () {
      for (var i = 0; i < 400; i++) {
        final copy = Uint8List.fromList(good);
        for (var k = 0; k < 1 + random.nextInt(8); k++) {
          copy[random.nextInt(copy.length)] = random.nextInt(256);
        }
        final doc = pdf(copy);
        expect(doc.contentHash, hasLength(64));
      }
    });

    test('pathological structures: deep nesting, reference loops, a page tree cycle', () {
      final deep = '%PDF-1.4\n1 0 obj\n${'[' * 5000}\nendobj\n';
      expect(pdf(Uint8List.fromList(latin1.encode(deep))).status, ExtractionStatus.damaged);
      const loop =
          '%PDF-1.4\n1 0 obj\n<< /Type /Catalog /Pages 2 0 R >>\nendobj\n2 0 obj\n<< /Type /Pages /Kids [2 0 R 3 0 R] >>\nendobj\n'
          '3 0 obj\n4 0 R\nendobj\n4 0 obj\n3 0 R\nendobj\ntrailer\n<< /Root 1 0 R >>\n';
      expect(pdf(Uint8List.fromList(latin1.encode(loop))).status, ExtractionStatus.damaged);
      final unclosed = '%PDF-1.4\n1 0 obj\n<< /Type /Catalog /Pages 2 0 R\n2 0 obj\n(${'(' * 3000}';
      expect(ExtractionStatus.values, contains(pdf(Uint8List.fromList(latin1.encode(unclosed))).status));
    });

    test('a slow file stops at the time limit', () {
      final doc = pdf(
        pdfWithPages([for (var i = 0; i < 50; i++) List.filled(2000, line('word')).join()]),
        const ExtractionLimits(maxDuration: Duration(milliseconds: 1)),
      );
      expect(doc.status, ExtractionStatus.partial);
      expect(doc.limit, isIn([ExtractionLimit.time, ExtractionLimit.operators]));
    });
  });

  group('text and CSV', () {
    test('one page, line endings unified, UTF-8 or Windows-1252', () {
      final txt = readDocument(
        Uint8List.fromList(utf8.encode('Offsite notes\r\nParking: 12 spaces\r\n')),
        mimeType: 'text/plain',
        fileName: 'Notes.txt',
      );
      expect(txt.status, ExtractionStatus.complete);
      expect(txt.format, DocumentFormat.text);
      expect(txt.pages.single.text, 'Offsite notes\nParking: 12 spaces');
      final cp = readDocument(Uint8List.fromList([0x43, 0x61, 0x66, 0xE9, 0x20, 0x80, 0x35]), mimeType: 'text/plain');
      expect(cp.pages.single.text, 'Café €5');
      final csv = readDocument(
        Uint8List.fromList(utf8.encode('Item,Cost\nVenue,"1,200.00"\n')),
        mimeType: 'text/csv',
        fileName: 'b.csv',
      );
      expect(csv.format, DocumentFormat.csv);
      expect(csv.pages.single.text, contains('Venue,"1,200.00"'));
    });

    test('a long file is cut at the character limit and says so', () {
      final doc = readDocument(
        Uint8List.fromList(utf8.encode('a' * 1000)),
        mimeType: 'text/plain',
        limits: const ExtractionLimits(maxCharacters: 100),
      );
      expect(doc.status, ExtractionStatus.partial);
      expect(doc.limit, ExtractionLimit.characters);
      expect(doc.pages.single.text, hasLength(100));
    });

    test('empty text has no text', () {
      expect(
        readDocument(Uint8List.fromList(utf8.encode(' \n ')), mimeType: 'text/plain').status,
        ExtractionStatus.noText,
      );
    });
  });

  test('the same bytes have the same identity whatever their name; different bytes differ', () {
    final a = pdfWithPages([line('Initial rate: 4.29% fixed')]);
    final b = pdfWithPages([line('Initial rate: 4.19% fixed')]);
    expect(a.length, b.length); // same name and size in mail, different contents
    final ra = readDocument(a, mimeType: 'application/pdf', fileName: 'illustration.pdf');
    final rb = readDocument(b, mimeType: 'application/pdf', fileName: 'illustration.pdf');
    final rc = readDocument(a, mimeType: 'application/pdf', fileName: 'renamed.pdf');
    expect(ra.contentHash, isNot(rb.contentHash));
    expect(ra.contentHash, rc.contentHash);
    expect(ra.version, extractorVersion);
  });
}
