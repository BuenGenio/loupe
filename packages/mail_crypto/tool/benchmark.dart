// Times what reading and sending encrypted mail costs: unlocking keys,
// decrypting and verifying messages of typical sizes, and composing them.
//
//   dart run tool/benchmark.dart                 # JIT, like `dart test`
//   dart compile exe tool/benchmark.dart -o /tmp/loupe-bench && /tmp/loupe-bench
//                                                # AOT, like the app's release build
//
// An argument limits the largest attachment, in KB (default 5120).
//
// Run from packages/mail_crypto (it reads test/fixtures). Each figure is the
// best of a few runs, in milliseconds.
// ignore_for_file: avoid_print
import 'dart:convert';
import 'dart:io';
import 'dart:math';
import 'dart:typed_data';

import 'package:mail_crypto/mail_crypto.dart';
import 'package:mail_imap/mail_imap.dart' show MimeMessageComposer;
import 'package:mail_model/mail_model.dart';

const pgp = DartPgBackend();
const smime = DartSmimeBackend();

Uint8List fixture(String path) => File('test/fixtures/$path').readAsBytesSync();
PgpKey key(String path) => pgp.readKeys(fixture(path)).single;

/// The best of [runs] runs of [work], in milliseconds (one more first, to warm up).
double best(void Function() work, {int runs = 3}) {
  work();
  var fastest = double.infinity;
  for (var i = 0; i < runs; i++) {
    final watch = Stopwatch()..start();
    work();
    fastest = min(fastest, watch.elapsedMicroseconds / 1000);
  }
  return fastest;
}

void row(String what, double ms) => print('${what.padRight(64)} ${ms.toStringAsFixed(1).padLeft(9)} ms');

final class _Keys implements PgpSendKeys {
  _Keys(this.state, this.signer);
  @override
  final KeyringState state;
  final PgpKey signer;
  @override
  PgpKey? unlockedKey(String fingerprint) => signer.fingerprint == fingerprint ? signer : null;
}

void main(List<String> args) {
  final maxKb = args.isEmpty ? 5120 : int.parse(args.first);
  print(
    'Loupe crypto benchmark (${Platform.version.split(' ').first}, ${Platform.operatingSystem}, '
    '${Platform.numberOfProcessors} cores, ${const bool.fromEnvironment('dart.vm.product') ? 'AOT' : 'JIT'})',
  );

  // Keys -------------------------------------------------------------------
  final aliceSecret = key('thunderbird/keys/alice@openpgp.example-0xf231550c4f47e38e-secret.asc');
  final alicePublic = key('thunderbird/keys/alice@openpgp.example-0xf231550c4f47e38e-pub.asc');
  final bobSecret = key('thunderbird/keys/bob@openpgp.example-0xfbfcc82a015e7330-secret.asc');
  final bobPublic = key('thunderbird/keys/bob@openpgp.example-0xfbfcc82a015e7330-pub.asc');
  final carolLocked = key('thunderbird/keys/carol@example.com-0x3099ff1238852b9f-secret.asc');
  final carolPublic = key('thunderbird/keys/carol@example.com-0x3099ff1238852b9f-pub.asc');
  final aliceLocked = key('thunderbird/keys/alice@openpgp.example-0xf231550c4f47e38e-secret-with-pp.asc');
  final gpgAlice = key('gpg/alice.sec.asc');
  final gpgBob = key('gpg/bob.sec.asc');
  final loupeKey = pgp.generate(userId: 'Bench <bench@example.org>', passphrase: 'correct horse');

  print('\nUnlocking a key (passphrase to secret key)');
  row(
    'Thunderbird export, Ed25519 + Curve25519 (${aliceLocked.algorithm})',
    best(() => pgp.unlock(aliceLocked, 'alice-passphrase')),
  );
  row('Thunderbird test key, ${carolLocked.algorithm}', best(() => pgp.unlock(carolLocked, 'x')));
  row('GnuPG 2.4, ${gpgAlice.algorithm}', best(() => pgp.unlock(gpgAlice, 'alice-pass')));
  row('GnuPG 2.4, ${gpgBob.algorithm}', best(() => pgp.unlock(gpgBob, 'bob-pass')));
  row('generated by Loupe, ${loupeKey.algorithm}', best(() => pgp.unlock(loupeKey, 'correct horse')));
  final carolSecret = pgp.unlock(carolLocked, 'x');

  // Messages ---------------------------------------------------------------
  final state = KeyringState(
    ownKeys: [alicePublic],
    publicKeys: [
      for (final k in [bobPublic, carolPublic])
        PublicKeyEntry(key: k, acceptance: KeyAcceptance.verified, added: DateTime(2026)),
    ],
  );
  final composer = PgpMessageComposer(MimeMessageComposer(), _Keys(state, aliceSecret), backend: pgp);
  const reader = PgpMimeReader(pgp);
  const alice = Identity(id: 'a', email: 'alice@openpgp.example', name: 'Alice');
  final random = Random(1);
  final text = List.generate(120, (i) => 'Line $i of a typical message, with some words to read. Grüße!').join('\n');

  OutgoingMessage message(int attachment, OutgoingSecurity security, {String to = 'bob@openpgp.example'}) =>
      OutgoingMessage(
        accountId: 'a',
        identityId: 'a',
        to: [EmailAddress(to)],
        subject: 'Numbers',
        text: text,
        attachments: [
          if (attachment > 0)
            OutgoingAttachment(
              filename: 'photo.jpg',
              mimeType: 'image/jpeg',
              data: Uint8List.fromList(List.generate(attachment, (_) => random.nextInt(256))),
            ),
        ],
        security: security,
      );

  Uint8List compose(OutgoingMessage m) => composer.compose(m, alice, messageId: 'bench@example.org');

  const sizes = [0, 100 * 1024, 1024 * 1024, 5 * 1024 * 1024];
  String label(int size) =>
      size == 0 ? '${(utf8.encode(text).length / 1024).round()} KB text' : '+ ${size ~/ 1024} KB attachment';

  print('\nReading (PgpMimeReader.read: decrypt, verify, MIME) and composing');
  const signEncrypt = OutgoingSecurity(encrypt: true, sign: true);
  const signOnly = OutgoingSecurity(sign: true);
  for (final size in sizes.where((s) => s <= maxKb * 1024)) {
    final runs = size >= 5 * 1024 * 1024 ? 1 : 3;
    final encrypted = message(size, signEncrypt);
    final raw = compose(encrypted);
    row('compose signed + encrypted, ${label(size)}', best(() => compose(encrypted), runs: runs));
    row(
      'decrypt + verify (Ed25519, Curve25519), ${label(size)}',
      best(() {
        final r = reader.read(raw, keys: [bobSecret], verifiers: [alicePublic]);
        if (!r.status.decrypted || r.status.signature?.status != PgpSignatureStatus.good) throw StateError('read');
        contentFromEntity(r.entity!, emailId: 'x');
      }, runs: runs),
    );
    final toCarol = compose(message(size, signEncrypt, to: 'carol@example.com'));
    row(
      'decrypt + verify (RSA 4096 recipient), ${label(size)}',
      best(() {
        final r = reader.read(toCarol, keys: [carolSecret], verifiers: [alicePublic]);
        if (!r.status.decrypted) throw StateError('read');
      }, runs: runs),
    );
    final signed = compose(message(size, signOnly));
    row(
      'verify multipart/signed, ${label(size)}',
      best(() {
        final r = reader.read(signed, verifiers: [alicePublic]);
        if (r.status.signature?.status != PgpSignatureStatus.good) throw StateError('verify');
      }, runs: runs),
    );
  }

  print('\nThunderbird test messages');
  for (final name in [
    'signed-by-0xfbfcc82a015e7330-encrypted-to-0xf231550c4f47e38e.eml',
    'encrypted-and-signed-alice-to-bob-nonascii.eml',
  ]) {
    final raw = fixture('thunderbird/eml/$name');
    final keys = name.contains('alice-to-bob') ? [bobSecret] : [aliceSecret];
    row(
      'read ${name.length > 48 ? '${name.substring(0, 45)}…' : name}',
      best(() {
        final r = reader.read(raw, keys: keys, verifiers: [alicePublic, bobPublic]);
        if (!r.status.decrypted) throw StateError('read');
      }),
    );
  }

  print('\nS/MIME');
  final smimeBundle = smime.readPkcs12(fixture('smime/bob-3des.p12'), 'bob-pass');
  row('import PKCS #12 (3DES, SHA-1 MAC)', best(() => smime.readPkcs12(fixture('smime/bob-3des.p12'), 'bob-pass')));
  row('import PKCS #12 (AES, PBKDF2)', best(() => smime.readPkcs12(fixture('smime/alice.p12'), 'alice-pass')));
  final bob = SmimeKeyPair(smimeBundle.keys.single.certificate, smimeBundle.keys.single.key);
  final enveloped = fixture('smime/signed-enveloped.eml');
  row(
    'read signed + enveloped (EC P-256 recipient)',
    best(() {
      if (!const SmimeReader(smime).read(enveloped, keys: [bob], now: DateTime.utc(2026, 10, 4)).status.decrypted) {
        throw StateError('read');
      }
    }),
  );
}
